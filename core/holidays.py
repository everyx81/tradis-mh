from PyQt6.QtCore import QDate

def is_holiday(date: QDate) -> bool:
    """
    주어진 날짜가 한국 공휴일(2024~2026)인지 판별합니다.
    (대체공휴일 포함)
    """
    y, m, d = date.year(), date.month(), date.day()
    
    # 2024년 공휴일
    if y == 2024:
        holidays_2024 = [
            (1, 1),   # 신정
            (2, 9), (2, 10), (2, 11), (2, 12), # 설날 + 대체공휴일
            (3, 1),   # 삼일절
            (4, 10),  # 국회의원 선거
            (5, 5), (5, 6), # 어린이날 + 대체공휴일
            (5, 15),  # 부처님 오신 날
            (6, 6),   # 현충일
            (8, 15),  # 광복절
            (9, 16), (9, 17), (9, 18), # 추석
            (10, 3),  # 개천절
            (10, 9),  # 한글날
            (12, 25)  # 성탄절
        ]
        return (m, d) in holidays_2024
        
    # 2025년 공휴일
    elif y == 2025:
        holidays_2025 = [
            (1, 1),   # 신정
            (1, 28), (1, 29), (1, 30), # 설날
            (3, 1), (3, 3), # 삼일절 + 대체공휴일
            (5, 5),   # 어린이날 & 부처님 오신 날 (겹침)
            (5, 6),   # 대체공휴일
            (6, 6),   # 현충일
            (8, 15),  # 광복절
            (10, 3),  # 개천절
            (10, 5), (10, 6), (10, 7), # 추석
            (10, 8), (10, 9), # 대체공휴일 + 한글날
            (12, 25)  # 성탄절
        ]
        return (m, d) in holidays_2025
        
    # 2026년 공휴일
    elif y == 2026:
        holidays_2026 = [
            (1, 1),   # 신정
            (2, 16), (2, 17), (2, 18), # 설날
            (3, 1), (3, 2), # 삼일절 + 대체공휴일
            (5, 5),   # 어린이날
            (5, 24), (5, 25), # 부처님 오신 날 + 대체공휴일
            (6, 3),   # 전국동시지방선거
            (6, 6),   # 현충일
            (7, 17),  # 제헌절 (2026년부터 공휴일 재지정)
            (8, 15), (8, 17), # 광복절 + 대체공휴일
            (9, 24), (9, 25), (9, 26), # 추석
            (10, 3), (10, 5), # 개천절 + 대체공휴일
            (10, 9),  # 한글날
            (12, 25)  # 성탄절
        ]
        return (m, d) in holidays_2026

    # 기본 공휴일 (매년 공통) — 제헌절은 2026년부터 재지정
    fixed_holidays = [
        (1, 1), (3, 1), (5, 5), (6, 6), (8, 15), (10, 3), (10, 9), (12, 25)
    ]
    if y >= 2026:
        fixed_holidays.append((7, 17))
    return (m, d) in fixed_holidays
